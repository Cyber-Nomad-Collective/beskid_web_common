import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(process.argv[2] ?? path.join(root, '../site/beskid_brand'));
const files = { brand: 'beskid-icon.svg', home: 'icon-website.svg', 'platform-spec': 'icon-platform-spec.svg', book: 'icon-book.svg', learn: 'icon-learn.svg', pckg: 'icon-pckg.svg', tracker: 'icon-tracker.svg', nexus: 'icon-nexus.svg' };
const bodies = Object.fromEntries(Object.entries(files).map(([key, filename]) => {
 const svg = fs.readFileSync(path.join(source, filename), 'utf8');
 if (!svg.includes('viewBox="0 0 120 120"')) throw new Error(`Unexpected icon dimensions: ${filename}`);
 const body = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/g, '').replace(/fill="#[0-9a-fA-F]{6}"/g, 'fill="currentColor"').trim();
 return [key, body];
}));
fs.writeFileSync(path.join(root, 'packages/beskid-ui-react/src/hub/brand-icons.generated.ts'), '// Generated by scripts/sync-brand-icons.mjs from site/beskid_brand SVGs. Do not edit.\nexport const BRAND_ICON_BODIES = '+JSON.stringify(bodies,null,'\t')+' as const;\n');
