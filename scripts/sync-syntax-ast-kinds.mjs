#!/usr/bin/env node
/**
 * Scans compiler/crates/beskid_analysis/src/syntax for top-level #[derive(AstNode)] enums
 * and emits spec-core/src/architecture/syntax-kinds.generated.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../..");
const syntaxRoot = path.join(
	repoRoot,
	"compiler/crates/beskid_analysis/src/syntax",
);
const outFile = path.join(
	__dirname,
	"../packages/spec-core/src/architecture/syntax-kinds.generated.ts",
);

/** Map enum name in Rust → architecture family key */
const FAMILY_BY_ENUM = {
	Expression: "Expression",
	Statement: "Statement",
	Node: "Item",
	Type: "Type",
};

function scanEnumVariants(source) {
	const variants = [];
	const enumMatch = source.match(
		/#\[derive\([^\]]*AstNode[^\]]*\)\][\s\S]*?pub enum (\w+) \{([\s\S]*?)\n\}/,
	);
	if (!enumMatch) return null;
	const body = enumMatch[2];
	const variantRe = /^\s+(\w+)\(/gm;
	let m;
	while ((m = variantRe.exec(body)) !== null) {
		variants.push(m[1]);
	}
	return { enumName: enumMatch[1], variants };
}

function collectFamilies() {
	const families = {};
	const scanFiles = [
		["Expression", "expressions/expression.rs"],
		["Statement", "statements/statement.rs"],
		["Item", "items/node.rs"],
		["Type", "types/type.rs"],
	];

	for (const [family, rel] of scanFiles) {
		const file = path.join(syntaxRoot, rel);
		if (!fs.existsSync(file)) {
			console.warn(`Missing ${file}`);
			continue;
		}
		const parsed = scanEnumVariants(fs.readFileSync(file, "utf8"));
		if (!parsed) {
			console.warn(`No AstNode enum in ${rel}`);
			continue;
		}
		const rustFamily = FAMILY_BY_ENUM[parsed.enumName] ?? family;
		families[rustFamily] = [...new Set(parsed.variants)].sort();
	}
	return families;
}

function emit(families) {
	const lines = [
		"// AUTO-GENERATED by scripts/sync-syntax-ast-kinds.mjs — do not edit",
		"",
		'import type { AstSyntaxFamily } from "./kinds.js";',
		"",
		"export const SYNTAX_KINDS_BY_FAMILY = {",
	];
	for (const family of ["Expression", "Statement", "Item", "Type"]) {
		const kinds = families[family] ?? [];
		lines.push(`\t${family}: [${kinds.map((k) => `"${k}"`).join(", ")}],`);
	}
	lines.push("} as const satisfies Record<AstSyntaxFamily, readonly string[]>;");
	lines.push("");
	lines.push("export type SyntaxKindByFamily = {");
	for (const family of ["Expression", "Statement", "Item", "Type"]) {
		const kinds = families[family] ?? [];
		if (kinds.length === 0) {
			lines.push(`\t${family}: string;`);
		} else {
			lines.push(
				`\t${family}: ${kinds.map((k) => `"${k}"`).join(" | ")};`,
			);
		}
	}
	lines.push("};");
	lines.push("");
	lines.push(
		"export function isSyntaxKindForFamily(family: AstSyntaxFamily, kind: string): boolean {",
	);
	lines.push(
		"\treturn (SYNTAX_KINDS_BY_FAMILY[family] as readonly string[]).includes(kind);",
	);
	lines.push("}");
	lines.push("");
	return `${lines.join("\n")}`;
}

const families = collectFamilies();
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, emit(families));
console.log(`Wrote ${outFile}`);
